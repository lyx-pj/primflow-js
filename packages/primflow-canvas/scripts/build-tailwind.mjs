import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { compile } from 'tailwindcss'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const primitivesDir = join(root, 'src/ui/primitives')
const outputFile = join(primitivesDir, 'tailwind.css.ts')

const tailwindDir = join(root, 'node_modules/tailwindcss')

/** Extract candidate utility tokens from primitive TypeScript sources. */
function extractCandidates() {
  const candidates = new Set()
  for (const name of readdirSync(primitivesDir)) {
    if (!name.endsWith('.ts') || name === 'tailwind.css.ts') continue
    const source = readFileSync(join(primitivesDir, name), 'utf8')
    for (const match of source.matchAll(/[^\s"'`<>]+/g)) {
      candidates.add(match[0])
    }
  }
  return [...candidates]
}

async function main() {
  const inputCss = `@import "tailwindcss/theme.css";\n@import "tailwindcss/utilities.css";\n`
  const compiled = await compile(inputCss, {
    loadStylesheet: async (id) => {
      const normalized = id.startsWith('tailwindcss/') ? id.slice('tailwindcss/'.length) : id
      const filePath = join(tailwindDir, normalized)
      return {
        path: filePath,
        base: tailwindDir,
        content: readFileSync(filePath, 'utf8'),
      }
    },
  })

  const cssOutput = compiled.build(extractCandidates())
  const escaped = cssOutput.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${')
  const banner = [
    '// Generated by scripts/build-tailwind.mjs. Do not edit manually.',
    "import { unsafeCSS } from 'lit'",
    '',
    `export const TAILWIND_UTILITIES_CSS = unsafeCSS(\`${escaped}\`)`,
    '',
  ].join('\n')

  writeFileSync(outputFile, banner, 'utf8')
  console.log(`Generated ${outputFile} (${cssOutput.length} bytes)`)
}

await main()
