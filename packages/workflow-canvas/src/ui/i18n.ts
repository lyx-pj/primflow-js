/** Language is instance configuration, never inferred from browser or process globals. */
export function translate(
  message: string,
  language: CanvasLanguage = 'en',
  values: Record<string, string | number> = {},
): string {
  const text = language === 'zh' ? chinese[message] ?? message : message
  return text.replace(/\{(\w+)\}/g, (placeholder, key: string) => String(values[key] ?? placeholder))
}
